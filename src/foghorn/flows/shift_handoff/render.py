"""Pure markdown rendering of the handoff (golden-tested)."""

from __future__ import annotations

from collections import Counter
from typing import Any


def _n(x: float) -> str:
    return str(int(x)) if float(x).is_integer() else f"{x:g}"


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    if not rows:
        return ["_none_"]
    return [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
        *("| " + " | ".join(r) + " |" for r in rows),
    ]


def render_handoff(state: dict[str, Any]) -> str:
    m: dict[str, float] = state.get("metrics") or {}
    incidents: list[dict[str, Any]] = state.get("incidents") or []
    approvals: list[dict[str, Any]] = state.get("approvals") or []
    alerts: list[dict[str, Any]] = state.get("alert_history") or []
    findings: list[dict[str, Any]] = state.get("findings") or []
    audit: list[dict[str, Any]] = state.get("audit") or []
    open_ = sorted((i for i in incidents if i["status"] != "resolved"), key=lambda i: (i["severity"], i["incident_id"]))
    done = sorted((i for i in incidents if i["status"] == "resolved"), key=lambda i: i["incident_id"])

    lines = [
        f"# Shift handoff - {state['shift_end']}",
        "",
        f"Window: {state['window_start']} -> {state['shift_end']} ({state['window_hours']} h, virtual time, UTC). "
        f"Incident source: {state['source']}. Generated by `shift_handoff` (deterministic, no LLM).",
        "",
        "## At a glance",
        "",
        *_table(
            ["Open", "Resolved", "Pending approvals", "Failed runs", "Alerts", "High alerts", "MTTR (min)"],
            [
                [
                    _n(m.get("incidents_open", 0)),
                    _n(m.get("incidents_resolved", 0)),
                    _n(m.get("approvals_pending", 0)),
                    _n(m.get("runs_failed", 0)),
                    _n(m.get("alerts_total", 0)),
                    _n(m.get("alerts_high", 0)),
                    _n(m.get("mttr_min_mean", 0)) if done else "n/a",
                ]
            ],
        ),
        "",
        "Open by severity: "
        + ", ".join(f"{s}={_n(m.get(f'open_{s.lower()}', 0))}" for s in ("SEV1", "SEV2", "SEV3", "SEV4")),
        "",
        "## Open incidents",
        "",
        *_table(
            ["Incident", "Sev", "Status", "Component", "Run", "Title"],
            [
                [
                    i["incident_id"],
                    i["severity"],
                    i["status"],
                    i.get("component") or "-",
                    i["run_status"],
                    i["title"] or "-",
                ]
                for i in open_
            ],
        ),
        "",
        "## Resolved this shift",
        "",
        *_table(
            ["Incident", "Sev", "Component", "Opened", "Resolved"],
            [
                [
                    i["incident_id"],
                    i["severity"],
                    i.get("component") or "-",
                    i.get("opened_at") or "-",
                    i.get("resolved_at") or "-",
                ]
                for i in done
            ],
        ),
        "",
        "## Pending approvals",
        "",
        *_table(
            ["Approval", "Kind", "Risk", "Incident", "Title"],
            [
                [a["approval_id"], a["kind"], a["risk"], str(a.get("incident_id") or "-"), a["title"] or "-"]
                for a in approvals
            ],
        ),
        "",
        "## Findings",
        "",
        *([f"- [{f['severity']}] {f['text']}" for f in findings] or ["_none_"]),
        "",
        "## Alert activity",
        "",
    ]
    if alerts:
        by_comp = Counter(a["component"] for a in alerts)
        high = Counter(a["component"] for a in alerts if a["severity"] in ("high", "critical"))
        lines += _table(
            ["Component", "Alerts", "High/critical", "First", "Last"],
            [
                [
                    c,
                    str(n),
                    str(high.get(c, 0)),
                    min(a["t"] for a in alerts if a["component"] == c),
                    max(a["t"] for a in alerts if a["component"] == c),
                ]
                for c, n in sorted(by_comp.items(), key=lambda kv: (-kv[1], kv[0]))[:10]
            ],
        )
    else:
        lines.append("_no alerts in the window_")
    lines += ["", "## Run log", "", *(f"- {a['node']}: {a['note']}" for a in audit)]
    return "\n".join(lines) + "\n"
